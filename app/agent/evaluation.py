DEFAULT_SUITE_PATH = Path("evaluations/agent/release_v1.json")


class AgentEvaluationConfigurationError(ValueError):
    """Raised when an evaluation suite does not satisfy its stable schema."""


@dataclass(frozen=True, slots=True)
class AgentEvaluationCaseResult:
    """Outcome and evidence for one curated evaluation case."""

    case_id: str
    category: str
    severity: str
    kind: str
    passed: bool
    checks: tuple[str, ...]
    failures: tuple[str, ...]
    actual: dict[str, Any]


@dataclass(frozen=True, slots=True)
class AgentEvaluationSummary:
    """Aggregate release-gate metrics for one suite execution."""

    total: int
    passed: int
    failed: int
    critical_total: int
    critical_passed: int
    overall_pass_rate: float
    critical_pass_rate: float
    required_overall_pass_rate: float
    required_critical_pass_rate: float
    release_gate_passed: bool
    category_results: dict[str, dict[str, int | float]]


@dataclass(frozen=True, slots=True)
class AgentEvaluationReport:
    """Machine-readable evidence generated by the agent evaluation runner."""

    schema_version: int
    suite_id: str
    suite_description: str
    generated_at: str
    summary: AgentEvaluationSummary
    cases: tuple[AgentEvaluationCaseResult, ...]

    def as_payload(self) -> dict[str, Any]:
        """Return a JSON-serializable representation of this report."""
        return asdict(self)


def load_agent_evaluation_suite(path: Path) -> dict[str, Any]:
    """Load and validate one versioned evaluation suite."""
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError as exc:
        raise AgentEvaluationConfigurationError(
            f"Agent evaluation suite was not found: {path}"
        ) from exc
    except json.JSONDecodeError as exc:
        raise AgentEvaluationConfigurationError(
            f"Agent evaluation suite is not valid JSON: {path}: {exc}"
        ) from exc

    if not isinstance(payload, dict):
        raise AgentEvaluationConfigurationError(
            "Agent evaluation suite must be a JSON object."
        )
    if payload.get("schema_version") != 1:
        raise AgentEvaluationConfigurationError(
            "Agent evaluation suite schema_version must be 1."
        )
    if not str(payload.get("suite_id") or "").strip():
        raise AgentEvaluationConfigurationError(
            "Agent evaluation suite requires suite_id."
        )
    cases = payload.get("cases")
    if not isinstance(cases, list) or not cases:
        raise AgentEvaluationConfigurationError(
            "Agent evaluation suite requires at least one case."
        )
    identifiers = [
        str(case.get("id") or "")
        for case in cases
        if isinstance(case, dict)
    ]
    if len(identifiers) != len(cases) or any(not item for item in identifiers):
        raise AgentEvaluationConfigurationError(
            "Every agent evaluation case requires a non-empty id."
        )
    duplicates = sorted(
        identifier
        for identifier, count in Counter(identifiers).items()
        if count > 1
    )
    if duplicates:
        raise AgentEvaluationConfigurationError(
            "Agent evaluation case ids must be unique: " + ", ".join(duplicates)
        )
    thresholds = payload.get("thresholds")
    if not isinstance(thresholds, dict):
        raise AgentEvaluationConfigurationError(
            "Agent evaluation suite requires thresholds."
        )
    for name in ("overall_pass_rate", "critical_pass_rate"):
        value = thresholds.get(name)
        if not isinstance(value, int | float) or not 0 <= float(value) <= 1:
            raise AgentEvaluationConfigurationError(
                f"Agent evaluation threshold {name} must be between 0 and 1."
            )
    return payload


def run_agent_evaluation_suite(suite: dict[str, Any]) -> AgentEvaluationReport:
    """Execute a validated suite without calling an LLM or Oracle endpoint."""
    results = tuple(_evaluate_case(case) for case in suite["cases"])
    thresholds = suite["thresholds"]
    summary = _summarize(
        results,
        required_overall=float(thresholds["overall_pass_rate"]),
        required_critical=float(thresholds["critical_pass_rate"]),
    )
    return AgentEvaluationReport(
        schema_version=1,
        suite_id=str(suite["suite_id"]),
        suite_description=str(suite.get("description") or ""),
        generated_at=datetime.now(UTC).isoformat(),
        summary=summary,
        cases=results,
    )


def write_agent_evaluation_report(
    report: AgentEvaluationReport,
    path: Path,
) -> None:
    """Write evaluation evidence atomically enough for local and CI use."""
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary_path = path.with_suffix(path.suffix + ".tmp")
    temporary_path.write_text(
        json.dumps(report.as_payload(), indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    temporary_path.replace(path)


def _evaluate_case(case: dict[str, Any]) -> AgentEvaluationCaseResult:
    case_id = str(case.get("id") or "")
    category = str(case.get("category") or "uncategorized")
    severity = str(case.get("severity") or "standard").casefold()
    kind = str(case.get("kind") or "")
    if severity not in {"standard", "critical"}:
        raise AgentEvaluationConfigurationError(
            f"Case {case_id} has unsupported severity: {severity}"
        )
    if kind == "intent_route":
        checks, failures, actual = _evaluate_intent_route(case_id, case)
    elif kind == "task_understanding":
        checks, failures, actual = _evaluate_task_understanding(case_id, case)
    elif kind == "artifact_ranking":
        checks, failures, actual = _evaluate_artifact_ranking(case_id, case)
    elif kind == "canonical_context":
        checks, failures, actual = _evaluate_canonical_context(case_id, case)
    elif kind == "entity_resolution":
        checks, failures, actual = _evaluate_entity_resolution(case_id, case)
    else:
        raise AgentEvaluationConfigurationError(
            f"Case {case_id} has unsupported kind: {kind}"
        )
    return AgentEvaluationCaseResult(
        case_id=case_id,
        category=category,
        severity=severity,
        kind=kind,
        passed=not failures,
        checks=tuple(checks),
        failures=tuple(failures),
        actual=actual,
    )


def _evaluate_intent_route(
    case_id: str,
    case: dict[str, Any],
) -> tuple[list[str], list[str], dict[str, Any]]:
    expected_tools = _string_set(case_id, case, "expected_tools")
    forbidden_tools = _string_set(
        case_id,
        case,
        "forbidden_tools",
        required=False,
    )
    decision = AgentIntentRouter.route(
        str(case.get("prompt") or ""),
        GRAPH_TOOL_NAMES,
        has_data_review_context=bool(case.get("has_data_review_context", False)),
        has_execution_context=bool(case.get("has_execution_context", False)),
        task_intent=str(case.get("task_intent") or "") or None,
        canonical_capability=(
            str(case.get("canonical_capability") or "") or None
        ),
        action_mode=str(case.get("action_mode") or "") or None,
    )
    actual_tools = frozenset(decision.tool_names)
    expected_intent = str(case.get("expected_intent") or "")
    checks: list[str] = []
    failures: list[str] = []
    if decision.intent.value == expected_intent:
        checks.append(f"intent={expected_intent}")
    else:
        failures.append(
            f"Expected intent {expected_intent}, received {decision.intent.value}."
        )
    if actual_tools == expected_tools:
        checks.append("least-privilege tool set matched")
    else:
        missing = sorted(expected_tools - actual_tools)
        unexpected = sorted(actual_tools - expected_tools)
        if missing:
            failures.append("Missing tools: " + ", ".join(missing) + ".")
        if unexpected:
            failures.append("Unexpected tools: " + ", ".join(unexpected) + ".")
    exposed_forbidden = sorted(actual_tools & forbidden_tools)
    if exposed_forbidden:
        failures.append(
            "Forbidden tools were exposed: " + ", ".join(exposed_forbidden) + "."
        )
    elif forbidden_tools:
        checks.append("forbidden tools withheld")
    return checks, failures, {
        "intent": decision.intent.value,
        "tools": sorted(actual_tools),
    }


def _evaluate_task_understanding(
    case_id: str,
    case: dict[str, Any],
) -> tuple[list[str], list[str], dict[str, Any]]:
    """Evaluate deterministic task continuity without an LLM or Oracle."""
    raw_turns = case.get("turns")
    if raw_turns is None:
        raw_turns = [case.get("prompt")]
    if not isinstance(raw_turns, list) or not raw_turns or any(
        not isinstance(item, str) or not item.strip() for item in raw_turns
    ):
        raise AgentEvaluationConfigurationError(
            f"Case {case_id} requires a non-empty prompt or turns list."
        )
    raw_today = str(case.get("today") or "").strip()
    try:
        evaluation_date = date.fromisoformat(raw_today) if raw_today else None
    except ValueError as exc:
        raise AgentEvaluationConfigurationError(
            f"Case {case_id} today must use YYYY-MM-DD."
        ) from exc
    messages = tuple(
        AgentMessage(
            message_id=index,
            conversation_id=f"evaluation-{case_id}",
            role=AgentMessageRole.USER,
            content=turn,
            created_at=datetime(2026, 1, 1, tzinfo=UTC),
        )
        for index, turn in enumerate(raw_turns, start=1)
    )
    result = AgentTaskInterpreter.interpret(messages, today=evaluation_date)
    checks: list[str] = []
    failures: list[str] = []

    expected_intent = str(case.get("expected_task_intent") or "")
    if result.intent.value == expected_intent:
        checks.append(f"task_intent={expected_intent}")
    else:
        failures.append(
            f"Expected task intent {expected_intent}, received {result.intent.value}."
        )

    expected_phase = str(case.get("expected_phase") or "")
    if result.phase.value == expected_phase:
        checks.append(f"task_phase={expected_phase}")
    else:
        failures.append(
            f"Expected task phase {expected_phase}, received {result.phase.value}."
        )

    expected_parameters = case.get("expected_parameters", {})
    if not isinstance(expected_parameters, dict):
        raise AgentEvaluationConfigurationError(
            f"Case {case_id} expected_parameters must be an object."
        )
    mismatched_parameters = {
        name: {"expected": value, "actual": result.parameters.get(name)}
        for name, value in expected_parameters.items()
        if result.parameters.get(name) != value
    }
    if mismatched_parameters:
        failures.append(
            "Task parameters did not match: "
            + json.dumps(mismatched_parameters, sort_keys=True)
            + "."
        )
    elif expected_parameters:
        checks.append("task parameters matched")

    expected_missing = tuple(
        str(item) for item in case.get("expected_missing_parameters", [])
    )
    if result.missing_parameters == expected_missing:
        checks.append("missing parameters matched")
    else:
        failures.append(
            "Expected missing parameters "
            f"{list(expected_missing)}, received {list(result.missing_parameters)}."
        )
    return checks, failures, {
        "task_intent": result.intent.value,
        "phase": result.phase.value,
        "confidence": result.confidence.value,
        "parameters": result.parameters,
        "missing_parameters": list(result.missing_parameters),
        "clarification_prompt": result.clarification_prompt,
    }


def _evaluate_artifact_ranking(
    case_id: str,
    case: dict[str, Any],
) -> tuple[list[str], list[str], dict[str, Any]]:
    raw_artifacts = case.get("artifacts")
    if not isinstance(raw_artifacts, list) or not raw_artifacts:
        raise AgentEvaluationConfigurationError(
            f"Case {case_id} requires artifacts."
        )
    artifacts = tuple(
        (str(item[0]), str(item[1]))
        for item in raw_artifacts
        if isinstance(item, list) and len(item) == 2
    )
    if len(artifacts) != len(raw_artifacts):
        raise AgentEvaluationConfigurationError(
            f"Case {case_id} artifacts must contain identifier/display-name pairs."
        )
    matches = recommend_artifacts(str(case.get("prompt") or ""), artifacts)
    checks: list[str] = []
    failures: list[str] = []
    if bool(case.get("expected_no_match", False)):
        if matches:
            failures.append(
                f"Expected no recommendation, received {matches[0].name}."
            )
        else:
            checks.append("ambiguous request produced no recommendation")
    else:
        expected_top = str(case.get("expected_top_artifact") or "")
        minimum_score = int(case.get("minimum_top_score", 0))
        if not matches:
            failures.append("Expected an artifact recommendation, received none.")
        else:
            top = matches[0]
            if top.name == expected_top:
                checks.append(f"top_artifact={expected_top}")
            else:
                failures.append(
                    f"Expected top artifact {expected_top}, received {top.name}."
                )
            if top.score >= minimum_score:
                checks.append(f"top_score>={minimum_score}")
            else:
                failures.append(
                    f"Expected top score >= {minimum_score}, received {top.score}."
                )
    return checks, failures, {
        "matches": [match.as_payload() for match in matches],
    }


def _evaluate_canonical_context(
    case_id: str,
    case: dict[str, Any],
) -> tuple[list[str], list[str], dict[str, Any]]:
    current = case.get("current")
    prior = case.get("prior")
    if not isinstance(current, dict) or (
        prior is not None and not isinstance(prior, dict)
    ):
        raise AgentEvaluationConfigurationError(
            f"Case {case_id} requires a current object and optional prior object."
        )
    result = AgentContextResolver.resolve(current, prior_context=prior)
    actual = result.model_dump(mode="json")
    checks: list[str] = []
    failures: list[str] = []
    expected_capability = str(case.get("expected_capability") or "")
    if actual["canonical_capability"] == expected_capability:
        checks.append(f"canonical_capability={expected_capability}")
    else:
        failures.append(
            "Expected canonical capability "
            f"{expected_capability}, received {actual['canonical_capability']}."
        )
    expected_parameters = case.get("expected_parameters", {})
    if not isinstance(expected_parameters, dict):
        raise AgentEvaluationConfigurationError(
            f"Case {case_id} expected_parameters must be an object."
        )
    for name, value in expected_parameters.items():
        if actual["parameters"].get(name) != value:
            failures.append(
                f"Expected parameter {name}={value!r}, received "
                f"{actual['parameters'].get(name)!r}."
            )
    if not failures and expected_parameters:
        checks.append("canonical parameters matched")
    return checks, failures, actual


def _evaluate_entity_resolution(
    case_id: str,
    case: dict[str, Any],
) -> tuple[list[str], list[str], dict[str, Any]]:
    raw_artifacts = case.get("artifacts")
    if not isinstance(raw_artifacts, list):
        raise AgentEvaluationConfigurationError(
            f"Case {case_id} requires artifacts."
        )
    artifacts = tuple(
        (str(item[0]), str(item[1]))
        for item in raw_artifacts
        if isinstance(item, list) and len(item) == 2
    )
    if len(artifacts) != len(raw_artifacts):
        raise AgentEvaluationConfigurationError(
            f"Case {case_id} artifacts must contain identifier/display-name pairs."
        )
    result = CatalogEntityResolver.resolve(
        str(case.get("candidate") or ""),
        artifacts,
        catalog_available=bool(case.get("catalog_available", True)),
    )
    expected_status = str(case.get("expected_status") or "")
    failures = []
    checks = []
    if result.status.value == expected_status:
        checks.append(f"entity_status={expected_status}")
    else:
        failures.append(
            f"Expected entity status {expected_status}, received "
            f"{result.status.value}."
        )
    expected_canonical = case.get("expected_canonical_name")
    if expected_canonical is not None:
        if result.canonical_name == str(expected_canonical):
            checks.append("canonical entity matched")
        else:
            failures.append(
                f"Expected canonical entity {expected_canonical}, received "
                f"{result.canonical_name}."
            )
    return checks, failures, result.as_payload()


def _string_set(
    case_id: str,
    case: dict[str, Any],
    field: str,
    *,
    required: bool = True,
) -> frozenset[str]:
    value = case.get(field)
    if value is None and not required:
        return frozenset()
    if not isinstance(value, list) or any(not isinstance(item, str) for item in value):
        raise AgentEvaluationConfigurationError(
            f"Case {case_id} field {field} must be a list of strings."
        )
    return frozenset(value)


def _summarize(
    results: tuple[AgentEvaluationCaseResult, ...],
    *,
    required_overall: float,
    required_critical: float,
) -> AgentEvaluationSummary:
    total = len(results)
    passed = sum(result.passed for result in results)
    critical = tuple(result for result in results if result.severity == "critical")
    critical_passed = sum(result.passed for result in critical)
    overall_rate = passed / total if total else 0.0
    critical_rate = critical_passed / len(critical) if critical else 1.0
    category_results: dict[str, dict[str, int | float]] = {}
    for category in sorted({result.category for result in results}):
        category_cases = tuple(
            result for result in results if result.category == category
        )
        category_passed = sum(result.passed for result in category_cases)
        category_results[category] = {
            "total": len(category_cases),
            "passed": category_passed,
            "failed": len(category_cases) - category_passed,
            "pass_rate": category_passed / len(category_cases),
        }
    return AgentEvaluationSummary(
        total=total,
        passed=passed,
        failed=total - passed,
        critical_total=len(critical),
        critical_passed=critical_passed,
        overall_pass_rate=overall_rate,
        critical_pass_rate=critical_rate,
        required_overall_pass_rate=required_overall,
        required_critical_pass_rate=required_critical,
        release_gate_passed=(
            overall_rate >= required_overall
            and critical_rate >= required_critical
        ),
        category_results=category_results,
    )


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Run the deterministic Oracle EPM agent release evaluation."
    )
    parser.add_argument(
        "--suite",
        type=Path,
        default=DEFAULT_SUITE_PATH,
        help="Path to the versioned evaluation suite JSON.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        help="Optional path for the machine-readable JSON report.",
    )
    parser.add_argument(
        "--fail-on-threshold",
        action="store_true",
        help="Exit with status 1 when the suite does not meet its thresholds.",
    )
    return parser


def main(argv: list[str] | None = None) -> int:
    """CLI entry point used locally and by the release CI workflow."""
    args = _build_parser().parse_args(argv)
    try:
        suite = load_agent_evaluation_suite(args.suite)
        report = run_agent_evaluation_suite(suite)
        if args.output:
            write_agent_evaluation_report(report, args.output)
    except AgentEvaluationConfigurationError as exc:
        print(f"Agent evaluation configuration error: {exc}", file=sys.stderr)
        return 2

    summary = report.summary
    gate = "PASS" if summary.release_gate_passed else "FAIL"
    print(
        f"Agent evaluation {report.suite_id}: {gate} - "
        f"{summary.passed}/{summary.total} passed; "
        f"critical {summary.critical_passed}/{summary.critical_total}."
    )
    for result in report.cases:
        if not result.passed:
            print(f"  FAIL {result.case_id}: {' '.join(result.failures)}")
    if args.fail_on_threshold and not summary.release_gate_passed:
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
